def rows(mask):
    r = [ln for ln in mask.strip("\n").split("\n") if ln]
    assert len(r) == 16, (len(r), r)
    assert all(len(ln) == 16 for ln in r), [len(ln) for ln in r]
    return r


def path(mask, ch):
    """Merge each row's runs of `ch` into rects, emitted as one path."""
    d = []
    for y, line in enumerate(rows(mask)):
        x = 0
        while x < 16:
            if line[x] == ch:
                w = 0
                while x + w < 16 and line[x + w] == ch:
                    w += 1
                d.append(f"M{x} {y}h{w}v1h-{w}z")
                x += w
            else:
                x += 1
    return "".join(d)


import sys

out = []
for name, mask in G.items():
    main, shade = path(mask, "#"), path(mask, "+")
    body = f'<path class="a" d="{main}"/>'
    if shade:
        body += f'<path class="b" d="{shade}"/>'
    out.append(f'<symbol id="i-{name}" viewBox="0 0 16 16">{body}</symbol>')

sprite = ('<svg class="sprite" aria-hidden="true" width="0" height="0">'
          + "".join(out) + "</svg>")

if __name__ != "__main__":
    pass  # imported for the masks alone (see tools/og.py)
elif "--preview" in sys.argv:
    # check the shapes without rendering anything
    for name, mask in G.items():
        print("\n" + name)
        for line in rows(mask):
            print("  " + line.replace("#", "█").replace("+", "▓").replace(".", " "))
else:
    print(sprite)
